// Helper function to get translated text
export const getTranslatedText = (key, language = 'en') => {
  const value = diversityTranslations[key];
  if (!value) return key;
  return value[language] || value.en;
};

// Helper function to get translated benefits array
export const getTranslatedBenefits = (level, language = 'en') => {
  const benefits = diversityTranslations.benefits[level];
  if (!benefits) return [];
  return benefits.map(benefit => benefit[language] || benefit.en);
};