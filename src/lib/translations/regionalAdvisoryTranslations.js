export const getTranslatedCropName = (cropName, language) => {
  const crop = regionalAdvisoryTranslations.crops[cropName];
  return crop ? (crop[language] || crop.en) : cropName;
};

// Helper function to get translated nutrient name
export const getTranslatedNutrient = (nutrient, language) => {
  const nutrientData = regionalAdvisoryTranslations.nutrients[nutrient];
  return nutrientData ? (nutrientData[language] || nutrientData.en) : nutrient;
};

// Helper function to get translated awareness note
export const getTranslatedAwarenessNote = (language) => {
  return regionalAdvisoryTranslations.awarenessNote[language] || regionalAdvisoryTranslations.awarenessNote.en;
};